async function syncAll51() {
  console.log('--- INICIANDO SINCRONIZACIÓN DE LOS 51 ATRACTIVOS OFICIALES ---');
  const pool = mysql.createPool(DB_URL);

  let insertados = 0;
  let actualizados = 0;

  for (const a of CANTON_LOJA_51_ATRACTIVOS) {
    const [existing] = await pool.query(
      'SELECT id, slug FROM atractivos_cantonales WHERE slug = ? LIMIT 1',
      [a.slug]
    );

    if (existing && existing.length > 0) {
      await pool.query(
        `UPDATE atractivos_cantonales 
         SET nombre = ?, canton = ?, cantonSlug = ?, categoria = ?, emoji = ?, 
             descripcion = ?, duracion = ?, distancia = ?, ruta = ?, imagenUrl = ?, 
             mapaUrl = ?, lat = ?, lng = ?, gradient = ?, activo = ?
         WHERE slug = ?`,
        [
          a.nombre, a.canton, a.cantonSlug, a.categoria, a.emoji,
          a.descripcion, a.duracion, a.distancia, a.ruta, a.imagenUrl,
          a.mapaUrl, a.lat, a.lng, a.gradient, a.activo, a.slug
        ]
      );
      actualizados++;
      console.log(`[UPDATED] ${a.slug} (${a.nombre})`);
    } else {
      await pool.query(
        `INSERT INTO atractivos_cantonales 
         (nombre, slug, canton, cantonSlug, categoria, emoji, descripcion,
          duracion, distancia, ruta, imagenUrl, mapaUrl, lat, lng, gradient, activo)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
        [
          a.nombre, a.slug, a.canton, a.cantonSlug, a.categoria, a.emoji,
          a.descripcion, a.duracion, a.distancia, a.ruta, a.imagenUrl,
          a.mapaUrl, a.lat, a.lng, a.gradient, a.activo
        ]
      );
      insertados++;
      console.log(`[INSERTED] ${a.slug} (${a.nombre})`);
    }
  }

  const [total] = await pool.query('SELECT COUNT(*) as c FROM atractivos_cantonales WHERE activo = 1');
  console.log(`\n=== SINCRONIZACIÓN EXITOSA ===`);
  console.log(`Insertados nuevos: ${insertados}`);
  console.log(`Actualizados/Enriquecidos: ${actualizados}`);
  console.log(`Total atractivos activos en la DB: ${total[0].c}`);

  await pool.end();
}

syncAll51().catch((err) => {
  console.error('Error fatal durante la sincronización:', err);
  process.exit(1);
});
